//! Validated identifiers. A value of one of these types has already passed its
//! grammar; nothing is ever "sanitised".

use std::fmt;

/// Names the field that failed. Never carries the rejected input, so it is
/// safe to log and to return to the caller.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct InvalidIdent(pub &'static str);

impl fmt::Display for InvalidIdent {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "invalid {}", self.0)
    }
}

impl std::error::Error for InvalidIdent {}

/// 1–63 bytes of `[a-z0-9-]`, not starting with `-`.
fn is_slug(s: &str) -> bool {
    let b = s.as_bytes();
    (1..=63).contains(&b.len())
        && b[0] != b'-'
        && b.iter()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || *c == b'-')
}

fn is_lower_hex(s: &str, len: usize) -> bool {
    s.len() == len
        && s.bytes()
            .all(|c| c.is_ascii_digit() || (b'a'..=b'f').contains(&c))
}

macro_rules! ident {
    ($(#[$doc:meta])* $name:ident, $field:literal, $valid:expr) => {
        $(#[$doc])*
        #[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
        pub struct $name(String);

        impl $name {
            pub fn new(s: &str) -> Result<Self, InvalidIdent> {
                let valid: fn(&str) -> bool = $valid;
                if valid(s) { Ok(Self(s.to_owned())) } else { Err(InvalidIdent($field)) }
            }

            pub fn as_str(&self) -> &str {
                &self.0
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(&self.0)
            }
        }
    };
}

ident!(
    /// A customer, as named in the policy file.
    CustomerId, "customer", is_slug
);
ident!(
    /// A system belonging to a customer.
    SystemId, "system", is_slug
);
ident!(
    /// An action on a system.
    ActionId, "action", is_slug
);
ident!(
    /// A calling agent. The daemon maps a peer uid to one of these.
    AgentId, "agent", is_slug
);
ident!(
    /// A registered passkey, as named by the daemon.
    CredentialId, "credential", is_slug
);
ident!(
    /// The name of a secret in the vault. Never the secret itself.
    SecretName, "secret name", is_slug
);
ident!(
    /// An agent's SSH public key, to be certified: `ssh-ed25519` and the 68
    /// base64 characters of an Ed25519 key, with no comment. Other key types
    /// are not accepted.
    SshPublicKey, "public key", |s| {
        s.strip_prefix("ssh-ed25519 ").is_some_and(|key| {
            key.len() == 68 && key.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'+' || c == b'/')
        })
    }
);
ident!(
    /// 128 random bits as 32 lowercase hex digits, generated by the daemon.
    RequestId, "request id", |s| is_lower_hex(s, 32)
);
ident!(
    /// What an action is aimed at: a repo, a host, a tenant. Only ever
    /// compared for equality against the policy, but still limited to
    /// 1–200 bytes of `[A-Za-z0-9._/:@-]` with no `..`.
    Target, "target", |s| {
        (1..=200).contains(&s.len())
            && !s.contains("..")
            && s.bytes().all(|c| c.is_ascii_alphanumeric() || b"._/:@-".contains(&c))
    }
);

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PinKind {
    /// A Git commit: 40 lowercase hex digits.
    Commit,
    /// An artefact digest: `sha256:` followed by 64 lowercase hex digits.
    Digest,
}

/// The exact thing a deploy is allowed to ship.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Pin {
    kind: PinKind,
    value: String,
}

impl Pin {
    pub fn commit(s: &str) -> Result<Self, InvalidIdent> {
        if is_lower_hex(s, 40) {
            Ok(Self {
                kind: PinKind::Commit,
                value: s.to_owned(),
            })
        } else {
            Err(InvalidIdent("commit"))
        }
    }

    pub fn digest(s: &str) -> Result<Self, InvalidIdent> {
        match s.strip_prefix("sha256:") {
            Some(hex) if is_lower_hex(hex, 64) => Ok(Self {
                kind: PinKind::Digest,
                value: s.to_owned(),
            }),
            _ => Err(InvalidIdent("digest")),
        }
    }

    pub fn kind(&self) -> PinKind {
        self.kind
    }

    pub fn as_str(&self) -> &str {
        &self.value
    }
}
